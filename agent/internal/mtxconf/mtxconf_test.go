func decode(t *testing.T, data []byte) map[string]any {
	t.Helper()
	var m map[string]any
	if err := yaml.Unmarshal(data, &m); err != nil {
		t.Fatalf("merged output is not YAML: %v\n%s", err, data)
	}
	return m
}

const base = `
api: yes
rtspAddress: :8554
paths:
  canal63:
    source: rtsp://cam/stream
    runOnDemand: ffmpeg -i x
  all_others:
`

func TestMergeKeepsTheBaseAndAddsPaths(t *testing.T) {
	out, err := Merge([]byte(base), []byte("paths:\n  canal65:\n    source: publisher\n"))
	if err != nil {
		t.Fatal(err)
	}
	m := decode(t, out)
	paths := m["paths"].(map[string]any)
	for _, want := range []string{"canal63", "canal65", "all_others"} {
		if _, ok := paths[want]; !ok {
			t.Errorf("path %s missing", want)
		}
	}
	if m["rtspAddress"] != ":8554" {
		t.Fatalf("base values lost: %v", m)
	}
	if !strings.HasPrefix(string(out), "# Generated by nodo-agent") {
		t.Fatal("missing generated header")
	}
}

// MediaMTX reads `yes` as a boolean; rewriting it as the string "yes" would break the configuration.
func TestScalarsAreKeptExactlyAsWritten(t *testing.T) {
	src := "# keep me\napi: yes\nhlsSegmentDuration: 1s\nreadTimeout: 10s\nrtspAddress: :8554\nport: 0777\nname: 'quoted'\n"
	out, err := Merge([]byte(src), []byte("logLevel: debug\n"))
	if err != nil {
		t.Fatal(err)
	}
	text := string(out)
	for _, want := range []string{"# keep me", "api: yes\n", "hlsSegmentDuration: 1s", "rtspAddress: :8554", "port: 0777", "name: 'quoted'", "logLevel: debug"} {
		if !strings.Contains(text, want) {
			t.Errorf("%q not preserved in\n%s", want, text)
		}
	}
	if strings.Contains(text, `"yes"`) {
		t.Fatal("yes became a string")
	}
}

func TestMergeChangesOneFieldOfAPathDefinedInTheBase(t *testing.T) {
	out, _ := Merge([]byte(base), []byte("paths:\n  canal63:\n    runOnDemand: ffmpeg -i y\n"))
	p := decode(t, out)["paths"].(map[string]any)["canal63"].(map[string]any)
	if p["runOnDemand"] != "ffmpeg -i y" || p["source"] != "rtsp://cam/stream" {
		t.Fatalf("deep merge failed: %v", p)
	}
}

