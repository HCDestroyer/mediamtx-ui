func TestRejectsWhatIsNotAMapping(t *testing.T) {
	for _, bad := range []string{"- a\n- b\n", "just text", "a: [unclosed"} {
		if _, err := Merge(nil, []byte(bad)); err == nil {
			t.Errorf("%q accepted", bad)
		}
	}
	if _, err := Merge(nil, []byte(strings.Repeat("a: 1\n", 300000))); err == nil {
		t.Error("huge document accepted")
	}
}

func TestCheckOverlayPaths(t *testing.T) {
	good := []string{"", "paths:\n  canal63:\n    source: publisher\n", "paths:\n  ~^cam_.*$:\n    source: publisher\n", "paths:\n  all_others:\n", "logLevel: info\n"}
	for _, g := range good {
		if err := CheckOverlay([]byte(g)); err != nil {
			t.Errorf("%q rejected: %v", g, err)
		}
	}
	bad := map[string]string{
		"paths:\n  'mi canal':\n    source: publisher\n": "not valid",
		"paths:\n  canal63: 7\n":                         "mapping",
		"paths: [a, b]\n":                                "mapping of path names",
	}
	for doc, want := range bad {
		if err := CheckOverlay([]byte(doc)); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("%q: got %v, want %q", doc, err, want)
		}
	}
}

func TestMaskHidesSecrets(t *testing.T) {
	out := string(Mask([]byte("srtPassphrase: hunter2hunter2\nrtmpAddress: :1935\n    publishPass: abc\n  pass: other\nsource: srt://h?passphrase=x\n")))
	for _, leak := range []string{"hunter2", "abc", "other"} {
		if strings.Contains(out, leak) {
			t.Errorf("%s leaked: %s", leak, out)
		}
	}
	if !strings.Contains(out, "rtmpAddress: :1935") {
		t.Fatal("masked too much")
	}
}

func newManager(t *testing.T, baseText string, v Validator) (*Manager, Paths) {
	t.Helper()
	dir := t.TempDir()
	p := Paths{Overlay: filepath.Join(dir, "nodo", "overlay.yml"), Out: filepath.Join(dir, "nodo", "mediamtx.yml")}
	if baseText != "" {
		p.Base = filepath.Join(dir, "mediamtx.yml")
		if err := os.WriteFile(p.Base, []byte(baseText), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	m, err := New(p, v)
	if err != nil {
		t.Fatal(err)
	}
	return m, p
}

func TestApplyWritesTheMergedFileAndNeverTouchesTheBase(t *testing.T) {
	m, p := newManager(t, base, nil)
	before, _ := os.ReadFile(p.Base)
	if err := m.Apply("paths:\n  nuevo:\n    source: publisher\n"); err != nil {
		t.Fatal(err)
	}
	out, _ := os.ReadFile(p.Out)
	paths := decode(t, out)["paths"].(map[string]any)
	if _, ok := paths["nuevo"]; !ok || paths["canal63"] == nil {
		t.Fatalf("merged file wrong: %s", out)
	}
	after, _ := os.ReadFile(p.Base)
	if string(before) != string(after) {
		t.Fatal("the operator's mediamtx.yml was modified")
	}
	st, _ := m.State()
	if !strings.Contains(st.Overlay, "nuevo") || !st.BaseFound || !st.OutFound {
		t.Fatalf("state %+v", st)
	}
}

func TestInvalidConfigurationChangesNothing(t *testing.T) {
	var asked []string
	reject := func(path string) error {
		data, _ := os.ReadFile(path)
		asked = append(asked, string(data))
		if strings.Contains(string(data), "badParam") {
			return &InvalidError{Message: "json: unknown field \"badParam\""}
		}
		return nil
	}
	m, p := newManager(t, base, reject)
	if err := m.Apply("logLevel: debug\n"); err != nil {
		t.Fatal(err)
	}
	good, _ := os.ReadFile(p.Out)
	goodOverlay, _ := os.ReadFile(p.Overlay)

	err := m.Apply("badParam: 1\n")
	var invalid *InvalidError
	if !errors.As(err, &invalid) || !strings.Contains(invalid.Message, "badParam") {
		t.Fatalf("got %v", err)
	}
	if now, _ := os.ReadFile(p.Out); string(now) != string(good) {
		t.Fatal("a rejected configuration replaced the running one")
	}
	if now, _ := os.ReadFile(p.Overlay); string(now) != string(goodOverlay) {
		t.Fatal("a rejected overlay was saved")
	}
	entries, _ := os.ReadDir(filepath.Dir(p.Out))
	for _, e := range entries {
		if strings.HasPrefix(e.Name(), ".candidate") {
			t.Fatalf("candidate file left behind: %s", e.Name())
		}
	}
	if len(asked) < 2 {
		t.Fatal("the validator was not consulted")
	}
	if err := m.Apply("paths:\n  'bad name':\n"); err == nil {
		t.Fatal("structural error accepted")
	}
}

