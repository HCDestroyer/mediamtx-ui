// Package mtxconf builds the configuration MediaMTX runs with from two files: the operator's own
// mediamtx.yml (never modified) and an additional file owned by the agent. MediaMTX has no include
// directive, so the agent writes the merged result to a third file and MediaMTX is started with that one.
package mtxconf

import (
	"bytes"
	"errors"
	"fmt"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

const maxSize = 1 << 20

// ErrNotMapping is returned when a document is valid YAML but not a mapping of parameters.
var ErrNotMapping = errors.New("the document must be a mapping of parameters (name: value)")

// parse reads a document into a mapping node. Working on nodes (not on Go values) keeps every scalar
// exactly as written (`yes` stays `yes`, durations and numbers are not reformatted) and keeps comments.
func parse(data []byte, what string) (*yaml.Node, error) {
	if len(data) > maxSize {
		return nil, fmt.Errorf("%s is larger than %d KB", what, maxSize>>10)
	}
	empty := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	if len(bytes.TrimSpace(data)) == 0 {
		return empty, nil
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s is not valid YAML: %w", what, err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) == 0 {
		return empty, nil
	}
	root := doc.Content[0]
	if root.Kind == yaml.ScalarNode && root.Tag == "!!null" {
		return empty, nil
	}
	if root.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%s: %w", what, ErrNotMapping)
	}
	return root, nil
}

func parseMapping(data []byte, what string) (map[string]any, error) {
	root, err := parse(data, what)
	if err != nil {
		return nil, err
	}
	var m map[string]any
	if err := root.Decode(&m); err != nil {
		return nil, fmt.Errorf("%s is not valid YAML: %w", what, err)
	}
	if m == nil {
		m = map[string]any{}
	}
	return m, nil
}

// Merge applies the overlay on top of the base. Mappings merge key by key (so one path can change a
// single field of a path defined in the base), any other value replaces, and a null in the overlay
// removes the key (or the whole path) from the result.
func Merge(base, overlay []byte) ([]byte, error) {
	b, err := parse(base, "the base configuration")
	if err != nil {
		return nil, err
	}
	o, err := parse(overlay, "the additional configuration")
	if err != nil {
		return nil, err
	}
	mergeNodes(b, o)
	var buf bytes.Buffer
	buf.WriteString("# Generated by nodo-agent from your mediamtx.yml plus the additional file. Do not edit: changes are overwritten.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(b); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func isNull(n *yaml.Node) bool { return n.Kind == yaml.ScalarNode && n.Tag == "!!null" }

func keyIndex(m *yaml.Node, key string) int {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return i
		}
	}
	return -1
}

// mergeNodes merges overlay (a mapping) into base (a mapping), in place.
func mergeNodes(base, overlay *yaml.Node) {
	for i := 0; i+1 < len(overlay.Content); i += 2 {
		key, val := overlay.Content[i], overlay.Content[i+1]
		at := keyIndex(base, key.Value)
		switch {
		case isNull(val):
			if at >= 0 {
				base.Content = append(base.Content[:at], base.Content[at+2:]...)
			}
		case val.Kind == yaml.MappingNode && at >= 0 && base.Content[at+1].Kind == yaml.MappingNode:
			mergeNodes(base.Content[at+1], val)
		case val.Kind == yaml.MappingNode:
			prune(val)
			setKey(base, at, key, val)
		default:
			setKey(base, at, key, val)
		}
	}
}

func setKey(base *yaml.Node, at int, key, val *yaml.Node) {
	if at >= 0 {
		base.Content[at+1] = val
		return
	}
	base.Content = append(base.Content, key, val)
}

// prune drops null entries of an overlay mapping that has nothing to merge into.
func prune(m *yaml.Node) {
	kept := m.Content[:0]
	for i := 0; i+1 < len(m.Content); i += 2 {
		if isNull(m.Content[i+1]) {
			continue
		}
		if m.Content[i+1].Kind == yaml.MappingNode {
			prune(m.Content[i+1])
		}
		kept = append(kept, m.Content[i], m.Content[i+1])
	}
	m.Content = kept
}

var pathName = regexp.MustCompile(`^(all|all_others|~.+|[A-Za-z0-9_\-./:]+)$`)

// CheckOverlay catches mistakes before MediaMTX sees them: valid YAML, a mapping, and well-formed paths.
func CheckOverlay(overlay []byte) error {
	m, err := parseMapping(overlay, "the additional configuration")
	if err != nil {
		return err
	}
	if p, ok := m["paths"]; ok && p != nil {
		paths, ok := p.(map[string]any)
		if !ok {
			return errors.New("paths must be a mapping of path names")
		}
		for name, conf := range paths {
			if !pathName.MatchString(name) {
				return fmt.Errorf("path name %q is not valid (letters, digits and _-./: only; start with ~ for a regular expression)", name)
			}
			if _, ok := conf.(map[string]any); !ok && conf != nil {
				return fmt.Errorf("path %q must be a mapping of parameters or null", name)
			}
		}
	}
	return nil
}

var secretKey = regexp.MustCompile(`(?i)(pass|secret|token|passphrase|psk)`)

// Mask replaces the values of secret-looking parameters so a configuration can be shown or logged.
func Mask(doc []byte) []byte {
	var lines []string
	for _, line := range strings.Split(string(doc), "\n") {
		if i := strings.Index(line, ":"); i > 0 && secretKey.MatchString(line[:i]) && strings.TrimSpace(line[i+1:]) != "" {
			line = line[:i+1] + " '***'"
		}
		lines = append(lines, line)
	}
	return []byte(strings.Join(lines, "\n"))
}
