// HTTP play screen against the demo server and its simulated agent.
const { chromium } = require('playwright');
const fs = require('fs');
const URL = process.env.NODO_URL || 'http://127.0.0.1:4173/';
const SHOTS = process.env.NODO_SHOTS || '/tmp';
const log = [];
const check = (n, ok, x = '') => log.push(`${ok ? 'PASS' : 'FAIL'} ${n} ${x}`);

(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 1400 }, permissions: ['clipboard-read', 'clipboard-write'], acceptDownloads: true });
  await ctx.addInitScript(() => localStorage.setItem('nodo:auth-skipped', '1'));
  const page = await ctx.newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(String(e)));

  // HeroUI hides the native input of a switch: the visible control is its label.
  const toggle = (name) => page.locator('label', { hasText: name }).first().click();

  await page.goto(URL);
  await page.getByRole('button', { name: 'Probar con datos de ejemplo' }).click();
  await page.waitForSelector('text=/3 de 5 en vivo/', { timeout: 10000 });
  await page.getByRole('link', { name: 'Reproducción' }).first().click();
  const save = page.getByRole('button', { name: 'Guardar cambios' });
  await save.waitFor();
  check('starts off with nothing to save', await save.isDisabled());
  check('nobody is watching while it is off', /Nadie está viendo/.test(await page.innerText('main')));

  // turn it on, require users, add a user: validation first
  await toggle('Activar la reproducción HTTP');
  await toggle('Pedir usuario');
  await page.waitForSelector('text=Pedir usuario exige al menos un usuario.');
  check('auth without users is flagged and cannot be saved', await save.isDisabled());
  await page.getByLabel('Nombre del usuario').fill('ana');
  await page.getByRole('button', { name: 'Agregar usuario' }).click();
  await page.getByTestId('user-ana').waitFor();
  check('adding the user clears the problem', !(await page.innerText('main')).includes('Pedir usuario exige'));
  check('new user shows it gets a token on save', /Se genera al guardar/.test(await page.getByTestId('user-ana').innerText()));

  // pool + rules
  await page.getByRole('button', { name: 'Agregar pool' }).click();
  await page.getByLabel('Nombre del pool').fill('hotel');
  await page.getByLabel('Direcciones (una por línea) hotel').fill('192.168.10.0/24\nnot-an-ip');
  await page.waitForSelector('text=/«not-an-ip» no es una IP ni un rango válido/');
  check('a bad pool entry is reported with its pool', true);
  await page.getByLabel('Direcciones (una por línea) hotel').fill('192.168.10.0/24\n10.1.1.5');
  await page.getByRole('button', { name: 'Agregar regla' }).click();
  await page.getByLabel('IP o rango 1').fill('300.1.1.1');
  await page.waitForSelector('text=/Regla 1: «300.1.1.1» no es una IP/');
  check('a bad rule address is reported with its rule number', true);
  await page.getByLabel('IP o rango 1').fill('203.0.113.0/24');
  await page.getByRole('button', { name: 'Agregar regla' }).click();
  await page.getByLabel('IP o rango 2').fill('198.51.100.9');
  // move rule 2 above rule 1
  await page.getByRole('button', { name: 'Subir 2' }).click();
  check('rules can be reordered', (await page.getByLabel('IP o rango 1').inputValue()) === '198.51.100.9');
  await page.screenshot({ path: `${SHOTS}/play-config.png`, fullPage: true });

  await save.click();
  await page.waitForSelector('text=Configuración aplicada');
  check('saved; tokens generated by the agent', !/Se genera al guardar/.test(await page.getByTestId('user-ana').innerText()));
  check('save button is idle again', await save.isDisabled());

  // viewers appear once play is on; block one
  await page.getByTestId('viewer-2').waitFor();
  check('viewers are listed with address, service and user', /203\.0\.113\.77/.test(await page.getByTestId('viewer-2').innerText()) && /ana/.test(await page.getByTestId('viewer-1').innerText()));
  await page.getByTestId('viewer-2').getByRole('button', { name: 'Bloquear IP' }).click();
  await page.waitForSelector('text=Se bloqueó 203.0.113.77');
  await page.getByTestId('viewer-2').waitFor({ state: 'detached' });
  check('blocking a viewer adds a deny rule first and removes it', (await page.getByLabel('IP o rango 1').inputValue()) === '203.0.113.77');

  // playlist: user token in the link, M3U download with agent + MediaMTX channels
  const count = await page.getByTestId('playlist-count').innerText();
  check('playlist counts agent and MediaMTX channels', /canales: 1 del agente, 3 de MediaMTX/.test(count), count);
  await page.getByRole('button', { name: 'Copiar enlace de la lista' }).click();
  const link = await page.evaluate(() => navigator.clipboard.readText());
  check('copied link points at the agent playlist with the token', /\/play\/playlist\.m3u\?token=[0-9a-f]{32}$/.test(link), link);
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Descargar .m3u' }).click()]);
  const text = fs.readFileSync(await download.path(), 'utf8');
  check('downloaded file is an M3U', download.suggestedFilename() === 'nodo.m3u' && text.startsWith('#EXTM3U\n'));
  check('agent entries carry the token, MediaMTX entries are HLS', /\/play\/deportes-hd\?token=[0-9a-f]{32}/.test(text) && /:8888\/canal63\/index\.m3u8/.test(text), text.split('\n').slice(0, 6).join(' | '));
  await toggle('Incluir canales de MediaMTX (HLS)');
  check('MediaMTX channels can be left out', /canales: 1 del agente, 0 de MediaMTX/.test(await page.getByTestId('playlist-count').innerText()));

  // discard
  await toggle('Pedir usuario');
  await page.getByRole('button', { name: 'Descartar' }).click();
  check('discard restores the saved configuration', await save.isDisabled());

  await page.setViewportSize({ width: 390, height: 800 });
  await page.goto(URL + '#/settings');
  await page.getByRole('link', { name: 'Abrir' }).nth(0).click().catch(() => {});
  await page.goto(URL + '#/play');
  await save.waitFor();
  check('mobile: no horizontal scroll', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: `${SHOTS}/play-mobile.png` });

  check('no page errors', errors.length === 0, errors.join('|'));
  console.log(log.join('\n'));
  await browser.close();
  process.exit(log.some((l) => l.startsWith('FAIL')) ? 1 : 0);
})().catch((e) => { console.log(log.join('\n')); console.error('E2E ERROR', e.message.split('\n').slice(0, 6).join('\n')); process.exit(1); });
